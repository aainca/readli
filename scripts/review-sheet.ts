/**
 * Writes docs/word-review-sheet.txt: every word by skill and level, with
 * syllables, chunks, homophones and confusables, for the parent to check.
 * Run: npm run content:review
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { SKILL_IDS, SKILLS, SYLLABLE_LABELS, type SkillFile } from '../src/content/schema';

const root = resolve(import.meta.dirname, '..');
const dir = resolve(root, 'src/content/skills');
const lines: string[] = [];
lines.push('VOWEL MASTERY: WORD REVIEW SHEET');
lines.push('Generated by npm run content:review. Edit src/content/source/*.txt, then npm run content.');
lines.push('');
lines.push('Each line: word  =  syl-la-bles [type per syllable]  chunks: r-ai-n  split: VC/CV   (= homophones)   (! confusable: hint)');
lines.push('A leading * marks a held-out placement-test word. It is never used in practice.');
lines.push('');

let total = 0;
let currentSet = 0;
for (const skillId of SKILL_IDS) {
  const meta = SKILLS[skillId];
  if (meta.set !== currentSet) {
    currentSet = meta.set;
    lines.push('#'.repeat(78));
    lines.push(`SET ${currentSet}: ${currentSet === 1 ? 'VOWEL GROUPS' : 'WORD SKILLS'}`);
    lines.push('#'.repeat(78));
    lines.push('');
  }
  const file = JSON.parse(readFileSync(resolve(dir, `${meta.slug}.json`), 'utf8')) as SkillFile;
  lines.push('='.repeat(78));
  lines.push(`${skillId}  ${meta.name.toUpperCase()}  (${file.words.length} words${meta.shipsIn === 'v2' ? ', V2' : ''})`);
  lines.push('='.repeat(78));
  if (file.words.length === 0) {
    lines.push('  (stub: no words yet)');
    lines.push('');
    continue;
  }
  for (const level of meta.levels) {
    const words = file.words.filter((w) => w.level === level);
    const held = words.filter((w) => w.heldOut).length;
    lines.push(`--- Level ${level}  (${words.length - held} practice words, ${held} held out for the test) ---`);
    for (const w of words) {
      total += 1;
      const types = w.syllableTypes.map((t) => SYLLABLE_LABELS[t]).join(', ');
      let s = `${w.heldOut ? '* ' : '  '}${w.text.padEnd(12)} ${w.syllables.join('-').padEnd(14)} [${types}]  chunks: ${w.chunks.join('-')}`;
      if (w.division?.length) s += `  split: ${w.division.join(', ')}`;
      if (w.homophones?.length) s += `   (= ${w.homophones.join(', ')})`;
      if (w.confusables?.length) s += '   ' + w.confusables.map((c) => `(! ${c.heard}: ${c.hint})`).join(' ');
      lines.push(s);
    }
    lines.push('');
  }
}
lines.push(`TOTAL: ${total} words`);
mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/word-review-sheet.txt'), lines.join('\n') + '\n');
console.log(`wrote docs/word-review-sheet.txt (${total} words)`);
