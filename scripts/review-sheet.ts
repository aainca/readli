/**
 * Writes docs/word-review-sheet.txt: every word by group and level, with
 * syllables, chunks, homophones and confusables, for the parent to check.
 * Run: npm run content:review
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { GROUP_IDS, GROUPS, LEVELS, SYLLABLE_LABELS, type GroupFile } from '../src/content/schema';

const root = resolve(import.meta.dirname, '..');
const dir = resolve(root, 'src/content/groups');
const lines: string[] = [];
lines.push('VOWEL MASTERY: WORD REVIEW SHEET');
lines.push('Generated by npm run content:review. Edit src/content/source/*.txt, then npm run content.');
lines.push('');
lines.push('Each line: word  =  syl-la-bles [type per syllable]  chunks: r-ai-n   (= homophones)   (! confusable: hint)');
lines.push('');

let total = 0;
for (const group of GROUP_IDS) {
  const file = JSON.parse(readFileSync(resolve(dir, `${group}.json`), 'utf8')) as GroupFile;
  const meta = GROUPS[group];
  lines.push('='.repeat(78));
  lines.push(`${meta.name.toUpperCase()}  (${meta.kind}, ${file.words.length} words)`);
  lines.push('='.repeat(78));
  if (file.words.length === 0) {
    lines.push('  (stub: no words yet)');
    lines.push('');
    continue;
  }
  for (const level of LEVELS) {
    const words = file.words.filter((w) => w.level === level);
    if (level < meta.minLevel && words.length === 0) continue;
    lines.push(`--- Level ${level}  (${words.length} words) ---`);
    for (const w of words) {
      total += 1;
      const types = w.syllableTypes.map((t) => SYLLABLE_LABELS[t]).join(', ');
      let s = `  ${w.text.padEnd(12)} ${w.syllables.join('-').padEnd(14)} [${types}]  chunks: ${w.chunks.join('-')}`;
      if (w.homophones?.length) s += `   (= ${w.homophones.join(', ')})`;
      if (w.confusables?.length) s += '   ' + w.confusables.map((c) => `(! ${c.heard}: ${c.hint})`).join(' ');
      lines.push(s);
    }
    lines.push('');
  }
}
lines.push(`TOTAL: ${total} words`);
mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/word-review-sheet.txt'), lines.join('\n') + '\n');
console.log(`wrote docs/word-review-sheet.txt (${total} words)`);
